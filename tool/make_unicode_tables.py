"""Writes src/text/unicode_tables.c: the code point ranges of Unicode's letters (\\p{L}) and
numbers (\\p{N}), from Python's unicodedata, for the tokenisers' pre-tokenising patterns.

    python3 tool/make_unicode_tables.py
"""

import unicodedata
from pathlib import Path


def ranges(prefix: str) -> list[tuple[int, int]]:
    out, start = [], None
    for c in range(0x110000):
        ok = unicodedata.category(chr(c)).startswith(prefix)
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name: str, rs: list[tuple[int, int]]) -> str:
    items = [f"{{0x{a:X}u, 0x{b:X}u}}" for a, b in rs]
    lines, line = [], "   "
    for it in items:
        if len(line) + len(it) + 2 > 100:
            lines.append(line)
            line = "   "
        line += " " + it + ","
    lines.append(line)
    return (f"const rayo_unicode_range {name}[] = {{\n" + "\n".join(lines)
            + f"\n}};\nconst size_t {name}_count = sizeof {name} / sizeof {name}[0];\n")


out = Path(__file__).resolve().parent.parent / "src" / "text" / "unicode_tables.c"
out.write_text(
    f"/* Generated by tool/make_unicode_tables.py from Unicode {unicodedata.unidata_version}:\n"
    " * the ranges of the letters (general category L) and numbers (N). Do not edit. */\n"
    '#include "text/unicode.h"\n\n'
    + table("rayo_unicode_letters", ranges("L")) + "\n"
    + table("rayo_unicode_numbers", ranges("N")))
