static double horner(const double *c, int n, double t) {
  double v = c[n - 1];
  int i;
  for (i = n - 2; i >= 0; i--) v = v * t + c[i];
  return v;
}

float rayo_erff(float xf) {
  const double x = (double)xf;
  const double a = x < 0.0 ? -x : x;
  double r;
  if (a < 1.0) {
    r = a * horner(erf_small, 14, a * a);
  } else if (a < 1.75) {
    r = horner(erf_piece1, 19, a - 1.375);
  } else if (a < 2.5) {
    r = horner(erf_piece2, 19, a - 2.125);
  } else if (a < 3.25) {
    r = horner(erf_piece3, 19, a - 2.875);
  } else if (a < 4.0) {
    r = horner(erf_piece4, 19, a - 3.625);
  } else {
    r = 1.0;
  }
  return (float)(x < 0.0 ? -r : r);
}

float rayo_expf(float x) {
  return (float)exp((double)x);
}

float rayo_sqrtf(float x) {
  return (float)sqrt((double)x);
}
